"""Deterministic Mock AI Provider for testing and CI (Phase 15, Workstream E).

Provides reproducible, offline, zero-cost code generation with configurable behaviors:
- Standard passing generation
- Repair simulation (fails on initial attempt, fixes on repair)
- Dangerous code generation (tests AST scanner interceptor)
"""
from __future__ import annotations

from typing import Any, Dict, Optional

from skillfactory.ai.provider import AIProvider, CodeGenerationResult
from skillfactory.spec import SkillSpec


class MockAIProvider(AIProvider):
    """Deterministic offline AI Provider for tests and isolated verification."""

    def __init__(
        self,
        mode: str = "passing",  # "passing", "repair_needed", "dangerous", "failing"
    ) -> None:
        self.mode = mode
        self.repair_attempts = 0

    @property
    def provider_id(self) -> str:
        return "mock"

    @property
    def display_name(self) -> str:
        return "Deterministic Mock Provider (Offline / CI)"

    def is_available(self) -> bool:
        return True

    def generate_skill_code(
        self,
        spec: SkillSpec,
        prompt: str,
    ) -> CodeGenerationResult:
        if self.mode == "dangerous":
            # Generates dangerous eval call to test scanner interceptor
            script = f"""#!/usr/bin/env python3
import sys

def execute_payload(user_input: str) -> None:
    eval(user_input)

if __name__ == '__main__':
    execute_payload('1 + 1')
"""
            test = """import unittest
class TestDangerous(unittest.TestCase):
    def test_run(self):
        self.assertTrue(True)
if __name__ == '__main__':
    unittest.main()
"""
            return CodeGenerationResult(script_code=script, test_code=test, explanation="Generated dangerous code")

        if self.mode == "repair_needed":
            # Generates broken test initially
            script = f"""#!/usr/bin/env python3
import sys

def process_data(val: int) -> int:
    return val * 2

if __name__ == '__main__':
    print(process_data(5))
"""
            test = """import unittest
from scripts.main import process_data

class TestBroken(unittest.TestCase):
    def test_logic(self):
        # Deliberate failure to trigger repair loop
        self.assertEqual(process_data(5), 999)

if __name__ == '__main__':
    unittest.main()
"""
            return CodeGenerationResult(script_code=script, test_code=test, explanation="Initial draft needing repair")

        # Standard passing mode
        script = f"""#!/usr/bin/env python3
\"\"\"Auto-generated logic for {spec.name}.\"\"\"
import argparse
import json
import sys

def run_task(input_data: str) -> dict:
    return {{"status": "ok", "processed": input_data.strip().upper(), "length": len(input_data.strip())}}

def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="{spec.description}")
    parser.add_argument("text", nargs="?", default="hello world", help="Input text to process")
    parser.add_argument("--json", action="store_true", help="Output JSON")
    args = parser.parse_args(argv)
    res = run_task(args.text)
    if args.json:
        print(json.dumps(res, indent=2))
    else:
        print(f"[OK] Processed: {{res['processed']}} (length: {{res['length']}})")
    return 0

if __name__ == '__main__':
    sys.exit(main())
"""
        test = f"""\"\"\"Tests for {spec.name}.\"\"\"
import unittest
from pathlib import Path
import sys

script_path = Path(__file__).parent.parent / "scripts"
sys.path.insert(0, str(script_path))
from main import run_task

class TestAutoGenerated(unittest.TestCase):
    def test_run_task(self):
        res = run_task("hello")
        self.assertEqual(res["status"], "ok")
        self.assertEqual(res["processed"], "HELLO")
        self.assertEqual(res["length"], 5)

if __name__ == '__main__':
    unittest.main()
"""
        return CodeGenerationResult(script_code=script, test_code=test, explanation="Generated deterministic passing code")

    def repair_skill_code(
        self,
        spec: SkillSpec,
        current_script: str,
        current_test: str,
        error_log: str,
    ) -> CodeGenerationResult:
        self.repair_attempts += 1
        # Fix the assertion in repair_needed mode
        fixed_test = current_test.replace("999", "10")
        return CodeGenerationResult(
            script_code=current_script,
            test_code=fixed_test,
            explanation=f"Repaired broken assertion on attempt {self.repair_attempts}",
        )
